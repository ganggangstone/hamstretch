// 쳇바퀴. 계속 앉아서 일하는 상태를 나타내는 이 앱의 핵심 은유다.
// 도트를 손으로 찍지 않고 계산해서 만든다 — 회전 각도만 바꾸면 프레임이 나오므로
// 돌아가는 그림을 여러 장 그려둘 필요가 없다.
const WHEEL_R = 11.4;
const WHEEL_C = 11.5;

export function wheelLayer(angle) {
  const cells = [];

  // 바깥 테두리
  for (let y = 0; y < CELL; y++) {
    for (let x = 0; x < CELL; x++) {
      const d = Math.hypot(x - WHEEL_C, y - WHEEL_C);
      if (Math.abs(d - WHEEL_R) < 0.7) cells.push([x, y, 'g']);
    }
  }

  // 살 4개. 이것만 돌아가므로 바퀴가 구르는 것처럼 보인다.
  for (let k = 0; k < 4; k++) {
    const a = angle + (k * Math.PI) / 2;
    for (let t = 3; t < WHEEL_R - 1; t += 0.4) {
      const x = Math.round(WHEEL_C + Math.cos(a) * t);
      const y = Math.round(WHEEL_C + Math.sin(a) * t);
      cells.push([x, y, 'g']);
    }
  }

  return cells;
}

